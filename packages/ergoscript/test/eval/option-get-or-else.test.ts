/**
 * OptionGetOrElse eval — fixture-driven + inline tests (phase 2f medium Stop β Task 5).
 *
 * Tests the `OptionGetOrElse` arm of the evaluator. Unwraps Some, falls
 * back to default on None. V3-gated lazy default evaluation:
 *   - V<3 (eager): default always evaluated, cost always charged.
 *   - V3+  (lazy): default only evaluated when input is None.
 *
 * Cost: Fixed(20), charged BEFORE eval-input (Pattern A).
 * Sigma-rust ref: ergotree-interpreter/src/eval/option_get_or_else.rs:10-29
 *
 * Smoking-gun fixtures:
 *   option_get_or_else_some_v0_eager (cost=55) vs
 *   option_get_or_else_some_v3_lazy  (cost=30) — same Some-input, BinOp default,
 *   25-unit gap proves lazy gate.
 *
 * Fixtures generated by `fixture-gen/src/cmds/ergoscript/eval/option_get_or_else.rs`
 * (sigma-rust oracle; byte-equality check).
 */

import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseTree } from '../../src/wire/ergo-tree'
import { evaluate, evaluateWith } from '../../src/eval/evaluate'
import { evalExpr } from '../../src/eval/eval'
import { Env } from '../../src/eval/env'
import { makeContext } from '../../src/eval/eval-context'
import { hexToBytes, hydrateSValue, captureEvalError, rehydrateEvalOpts } from '../_helpers'

const __dirname = dirname(fileURLToPath(import.meta.url))

interface OptionGetOrElseFixtureEntry {
  name: string
  tree_bytes_hex: string
  opts_json: Record<string, unknown>
  expected_value_json: unknown
  expected_cost: number
  expected_error_code: string | null
}

interface OptionGetOrElseFixtureFile {
  corpus: string
  entries: OptionGetOrElseFixtureEntry[]
}

const FIXTURE_PATH = join(__dirname, '../fixtures/eval/option-get-or-else.json')
const fixture: OptionGetOrElseFixtureFile = JSON.parse(readFileSync(FIXTURE_PATH, 'utf-8'))

describe('OptionGetOrElse eval (phase 2f medium Stop β Task 5)', () => {
  for (const entry of fixture.entries) {
    it(entry.name, () => {
      const tree = parseTree(hexToBytes(entry.tree_bytes_hex))
      const opts = rehydrateEvalOpts(entry.opts_json)
      const ctx = makeContext(opts)

      if (entry.expected_error_code !== null) {
        const err = captureEvalError(() => evaluateWith(tree, ctx))
        expect(err.code).toBe(entry.expected_error_code)
      } else {
        const result = evaluateWith(tree, ctx)
        expect(result).toEqual(hydrateSValue(entry.expected_value_json))
        expect(ctx.jitCost).toBe(entry.expected_cost)
      }
    })
  }

  it("non-Option input throws 'option-input-not-option'", () => {
    const tree = {
      header: { version: 0 as const, hasSize: false, constantSegregation: false, rawHeader: 0 },
      constants: [] as [],
      constantTypes: [] as [],
      body: {
        tag: 'OptionGetOrElse' as const,
        input: {
          tag: 'Const' as const,
          tpe: { tag: 'SInt' as const },
          value: { kind: 'Int' as const, value: 5 },
        },
        default: {
          tag: 'Const' as const,
          tpe: { tag: 'SInt' as const },
          value: { kind: 'Int' as const, value: 0 },
        },
      },
    }
    const err = captureEvalError(() => evaluate(tree))
    expect(err.code).toBe('option-input-not-option')
  })

  it('V3+ lazy: Some-input returns value without evaluating cost-bearing default', () => {
    // Build OptionGetOrElse with a default that would throw if evaluated
    // (BinOp cost would exceed the limit if evaluated at V2).
    // V3 should not evaluate the default at all.
    // We construct by hand to control treeVersion directly.
    const inputExpr = {
      tag: 'Const' as const,
      tpe: { tag: 'SOption' as const, elem: { tag: 'SInt' as const } },
      value: {
        kind: 'Option' as const,
        elem: { tag: 'SInt' as const },
        value: { kind: 'Int' as const, value: 42 },
      },
    }
    const defaultExpr = {
      tag: 'Const' as const,
      tpe: { tag: 'SInt' as const },
      value: { kind: 'Int' as const, value: 99 },
    }
    const expr = {
      tag: 'OptionGetOrElse' as const,
      input: inputExpr,
      default: defaultExpr,
    }
    // At V3+ with a jitCostLimit just above the Some-path (OGOE=20 only, no default).
    // If lazy: total = 20 (OGOE) + 5 (Const/input) = 25. Passes with limit=25.
    // If eager: total = 20 + 5 (Const/input) + 5 (Const/default) = 30. Would pass but
    //   jitCost would be 30, not 25.
    const ctx = makeContext({ treeVersion: 3, jitCostLimit: 100 })
    const result = evalExpr(expr, Env.empty(), ctx)
    expect(result).toEqual({ kind: 'Int', value: 42 })
    // At V3, Const input costs 5, OGOE costs 20. Default Const(99) should NOT be evaluated.
    // Total = 20 (OGOE) + 5 (Const/input) = 25.
    expect(ctx.jitCost).toBe(25)
  })

  it('V<3 eager: Some-input DOES evaluate default (cost always charged)', () => {
    // Same structure at V2: Const input + Const default. Both should be evaluated.
    const inputExpr = {
      tag: 'Const' as const,
      tpe: { tag: 'SOption' as const, elem: { tag: 'SInt' as const } },
      value: {
        kind: 'Option' as const,
        elem: { tag: 'SInt' as const },
        value: { kind: 'Int' as const, value: 42 },
      },
    }
    const defaultExpr = {
      tag: 'Const' as const,
      tpe: { tag: 'SInt' as const },
      value: { kind: 'Int' as const, value: 99 },
    }
    const expr = {
      tag: 'OptionGetOrElse' as const,
      input: inputExpr,
      default: defaultExpr,
    }
    const ctx = makeContext({ treeVersion: 2, jitCostLimit: 100 })
    const result = evalExpr(expr, Env.empty(), ctx)
    expect(result).toEqual({ kind: 'Int', value: 42 })
    // At V2 (eager), OGOE(20) + Const/input(5) + Const/default(5) = 30.
    expect(ctx.jitCost).toBe(30)
  })

  it('V3+ lazy: None-input still evaluates default', () => {
    // Even at V3, when input is None, default must be evaluated.
    const inputExpr = {
      tag: 'Const' as const,
      tpe: { tag: 'SOption' as const, elem: { tag: 'SInt' as const } },
      value: {
        kind: 'Option' as const,
        elem: { tag: 'SInt' as const },
        value: null,
      },
    }
    const defaultExpr = {
      tag: 'Const' as const,
      tpe: { tag: 'SInt' as const },
      value: { kind: 'Int' as const, value: 99 },
    }
    const expr = {
      tag: 'OptionGetOrElse' as const,
      input: inputExpr,
      default: defaultExpr,
    }
    const ctx = makeContext({ treeVersion: 3 })
    const result = evalExpr(expr, Env.empty(), ctx)
    expect(result).toEqual({ kind: 'Int', value: 99 })
    // V3 None: OGOE(20) + Const/input(5) + Const/default(5) = 30.
    expect(ctx.jitCost).toBe(30)
  })
})
