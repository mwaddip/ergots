/**
 * Slice (collection slice) eval — fixture-driven test (phase 2f Coll HOFs Task 5).
 *
 * Tests the `Slice` arm of the evaluator. Slice returns a new Coll[T] that is
 * the intersection of `[from, until)` with the collection bounds.
 *
 * Scala-compat semantics (sigma-rust issue #724):
 *   - Does NOT throw on OOB from/until — clips silently.
 *   - from >= until → returns empty collection.
 *   - Empty input → always returns empty.
 *
 * Cost: `add_per_item_jit_cost(10, 2, 100, n_items)` where
 *   n_items = max(0, until - from) — the REQUESTED RANGE, not input length.
 * Pattern B-chunked: cost charged AFTER all three child evals.
 *
 * Sigma-rust ref: ergotree-interpreter/src/eval/coll_slice.rs:17-43
 *   let input_v = self.input.eval(env, ctx)?;      // line 17
 *   let from_v  = self.from.eval(env, ctx)?;       // line 18
 *   let until_v = self.until.eval(env, ctx)?;      // line 19
 *   let n_items = 0i32.max(until - from) as u32;  // line 31
 *   ctx.add_per_item_jit_cost(10, 2, 100, n_items)?; // line 32 — Pattern B-chunked
 *
 * Bug-7 (sigma-rust #724) regression: cost must scale with requested range
 * (until - from), NOT input length. The smoking-gun pair (entries 6+7) proves
 * this: same from/until against 5-item vs 1000-item input → identical cost.
 * See sigma-rust coll_slice.rs:167-211.
 *
 * Fixtures generated by `fixture-gen/src/cmds/ergoscript/eval/coll_slice.rs`
 * (sigma-rust oracle; byte-equality check for success entries).
 *
 * Entries:
 *   1.  coll_slice_happy           — [1,2,3,4][1..3] → [2,3]
 *   2.  coll_slice_neg_from        — [1,2,3,4][-1..3] → [1,2,3] (clipped, no throw)
 *   3.  coll_slice_until_oob       — [1,2,3,4][2..10] → [3,4] (clipped, no throw)
 *   4.  coll_slice_from_ge_until   — [1,2,3,4][3..1] → [] (n_items=0)
 *   5.  coll_slice_empty_input     — [][1..3] → [] (empty input)
 *   6.  coll_slice_smoking_gun_5   — [0..5][0..2] → [0,1] (smoking-gun A: small input)
 *   7.  coll_slice_smoking_gun_1k  — [0..1000][0..2] → [0,1] (smoking-gun B: large input)
 *      (entries 6+7: identical cost — proves cost ≠ f(input length))
 *   8.  coll_slice_large_range     — [0..5][0..200] → [0..5]; cost > entries 6+7
 *   9.  coll_slice_bound_not_int   — Slice(Coll, Bool_from, Int_until) → 'coll-slice-bound-not-int'
 *   10. coll_slice_not_coll        — Slice(Const(Int,42), Int_from, Int_until) → 'coll-input-not-coll'
 *   11. coll_slice_neg_until       — [1,2,3,4][0..-1] → [] (NEGATIVE until ⇒ empty; iter-30 regression)
 *   12. coll_slice_neg_until_from_mid — [10,20,30,40][1..-1] → [] (from in-range, negative until ⇒ empty)
 *
 * iter-30 (mainnet h=1,520,814 tx12/in0): a negative `until` made `Array.slice(from, neg)`
 * index from the END (non-empty), diverging from sigma-rust's `until.min(len) as usize` →
 * out-of-bounds range → None → empty. Surfaced as a +30 cost-drift (two empty-Coll[Long]
 * equalities sigma-rust saw as both-empty, our non-empty operand took the length-mismatch
 * short-circuit). Fixed in coll-slice.ts via an explicit `clippedFrom >= clippedUntil` guard.
 */

import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseTree } from '../../src/wire/ergo-tree'
import { evaluateWith } from '../../src/eval/evaluate'
import { makeContext } from '../../src/eval/eval-context'
import { hexToBytes, hydrateSValue, captureEvalError, rehydrateEvalOpts } from '../_helpers'

const __dirname = dirname(fileURLToPath(import.meta.url))

interface CollSliceFixtureEntry {
  name: string
  tree_bytes_hex: string
  opts_json: Record<string, unknown>
  expected_value_json: unknown
  expected_cost: number
  expected_error_code: string | null
}

interface CollSliceFixtureFile {
  corpus: string
  entries: CollSliceFixtureEntry[]
}

const FIXTURE_PATH = join(__dirname, '../fixtures/eval/coll-slice.json')
const fixture: CollSliceFixtureFile = JSON.parse(readFileSync(FIXTURE_PATH, 'utf-8'))

describe('Slice eval (phase 2f Coll HOFs Task 5)', () => {
  for (const entry of fixture.entries) {
    it(entry.name, () => {
      const tree = parseTree(hexToBytes(entry.tree_bytes_hex))
      const opts = rehydrateEvalOpts(entry.opts_json)
      const ctx = makeContext(opts)

      if (entry.expected_error_code !== null) {
        const err = captureEvalError(() => evaluateWith(tree, ctx))
        expect(err.code).toBe(entry.expected_error_code)
      } else {
        const result = evaluateWith(tree, ctx)
        expect(result).toEqual(hydrateSValue(entry.expected_value_json))
        expect(ctx.jitCost).toBe(entry.expected_cost)
      }
    })
  }

  // Smoking-gun: same (from, until) against different input sizes → identical cost.
  // Verifies bug-7 fix (sigma-rust #724): cost = f(requested range), NOT f(input length).
  // Per Task 4 review: use live-eval (not just fixture cost comparison) to prove
  // the evaluator itself charges correctly.
  it('smoking-gun: 5-elem and 1000-elem inputs with same [0..2] range produce identical cost', () => {
    const gun5Entry = fixture.entries.find(e => e.name === 'coll_slice_smoking_gun_5')!
    const gun1kEntry = fixture.entries.find(e => e.name === 'coll_slice_smoking_gun_1k')!

    // Live-eval each tree through the TS evaluator and compare the resulting costs.
    const ctx5 = makeContext(rehydrateEvalOpts(gun5Entry.opts_json))
    evaluateWith(parseTree(hexToBytes(gun5Entry.tree_bytes_hex)), ctx5)

    const ctx1k = makeContext(rehydrateEvalOpts(gun1kEntry.opts_json))
    evaluateWith(parseTree(hexToBytes(gun1kEntry.tree_bytes_hex)), ctx1k)

    expect(ctx5.jitCost).toBe(ctx1k.jitCost)
  })

  // Sanity: large requested range → higher cost than small requested range.
  it('large-range cost > smoking-gun cost (requested range drives cost, not clipped output)', () => {
    const gun5Entry = fixture.entries.find(e => e.name === 'coll_slice_smoking_gun_5')!
    const largeRangeEntry = fixture.entries.find(e => e.name === 'coll_slice_large_range')!

    const ctxSmall = makeContext(rehydrateEvalOpts(gun5Entry.opts_json))
    evaluateWith(parseTree(hexToBytes(gun5Entry.tree_bytes_hex)), ctxSmall)

    const ctxLarge = makeContext(rehydrateEvalOpts(largeRangeEntry.opts_json))
    evaluateWith(parseTree(hexToBytes(largeRangeEntry.tree_bytes_hex)), ctxLarge)

    expect(ctxLarge.jitCost).toBeGreaterThan(ctxSmall.jitCost)
  })
})
